#!/usr/bin/env python3
"""Merge multiple NeuralPVS GV/PVV dataset parts into one training dataset.

Use this after exporting a batch generated by generate_synthetic_neuralpvs_batch.py.
The merged dataset renumbers files consecutively:

    gv/0000_gv.bin.gz
    pvv/0000_pvv.bin.gz

By default files are copied. Pass --link on Linux to create symlinks instead,
which is much faster and avoids duplicating large datasets.
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import shutil
from pathlib import Path
from typing import Iterable, List, Tuple


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--plan", type=Path, default=None,
                        help="Export plan CSV produced by generate_synthetic_neuralpvs_batch.py.")
    parser.add_argument("--source-root", type=Path, default=None,
                        help="Folder containing exported part datasets. Used with --plan.")
    parser.add_argument("--inputs", type=Path, nargs="*", default=None,
                        help="Explicit exported dataset folders to merge.")
    parser.add_argument("--output-root", type=Path, required=True,
                        help="Dataset root that will receive the merged dataset folder.")
    parser.add_argument("--dataset-name", required=True)
    parser.add_argument("--link", action="store_true",
                        help="Create symlinks instead of copying files.")
    parser.add_argument("--overwrite", action="store_true")
    return parser.parse_args()


def planned_inputs(plan: Path, source_root: Path) -> List[Path]:
    rows = list(csv.DictReader(plan.open(newline="", encoding="utf-8")))
    inputs = []
    for row in rows:
        dataset_name = row.get("dataset_name")
        if not dataset_name:
            raise ValueError(f"Missing dataset_name in {plan}")
        inputs.append(source_root / dataset_name)
    return inputs


def sorted_pairs(dataset: Path) -> List[Tuple[Path, Path]]:
    gv_files = sorted((dataset / "gv").glob("*_gv.bin.gz"))
    pvv_files = sorted((dataset / "pvv").glob("*_pvv.bin.gz"))
    if len(gv_files) != len(pvv_files):
        raise ValueError(
            f"{dataset} has mismatched GV/PVV counts: {len(gv_files)} vs {len(pvv_files)}"
        )
    return list(zip(gv_files, pvv_files))


def place(src: Path, dst: Path, link: bool) -> None:
    if link:
        os.symlink(src, dst)
    else:
        shutil.copy2(src, dst)


def main() -> None:
    args = parse_args()
    if args.plan is None and not args.inputs:
        raise ValueError("Use --plan with --source-root, or pass --inputs.")
    if args.plan is not None and args.source_root is None:
        raise ValueError("--source-root is required with --plan.")

    inputs = planned_inputs(args.plan, args.source_root) if args.plan else list(args.inputs)
    missing = [p for p in inputs if not (p / "gv").is_dir() or not (p / "pvv").is_dir()]
    if missing:
        raise FileNotFoundError("Missing exported dataset folders:\n" + "\n".join(str(p) for p in missing))

    out = args.output_root / args.dataset_name
    if out.exists():
        if not args.overwrite:
            raise FileExistsError(f"{out} exists. Pass --overwrite to replace it.")
        shutil.rmtree(out)
    (out / "gv").mkdir(parents=True)
    (out / "pvv").mkdir(parents=True)

    sources = []
    index = 0
    for dataset in inputs:
        pairs = sorted_pairs(dataset)
        sources.append({"dataset": str(dataset), "samples": len(pairs)})
        for gv, pvv in pairs:
            place(gv.resolve(), out / "gv" / f"{index:04d}_gv.bin.gz", args.link)
            place(pvv.resolve(), out / "pvv" / f"{index:04d}_pvv.bin.gz", args.link)
            index += 1

    metadata = {
        "dataset_name": args.dataset_name,
        "sample_count": index,
        "merged_from": sources,
        "link_mode": args.link,
    }
    (out / "metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")

    print(f"Merged dataset: {out}")
    print(f"Samples       : {index}")
    print(f"GV files      : {len(list((out / 'gv').glob('*_gv.bin.gz')))}")
    print(f"PVV files     : {len(list((out / 'pvv').glob('*_pvv.bin.gz')))}")
    print(f"Mode          : {'symlink' if args.link else 'copy'}")


if __name__ == "__main__":
    main()
